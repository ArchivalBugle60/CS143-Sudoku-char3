
public class SudokuSolverEngine {

   public static void main(String[] args) {
      // Here I have called my class `MySudokuBoard` if you named your class
      // differently, modify the line below to use your own class name
      SudokuBoard board = new SudokuBoard("boards/row-violation.sdk"); // ok both boards of fast and v fast work
      System.out.println("Initial board");
      System.out.println(board);
      System.out.println();
      
      // checks if board isnt valid and if so prints cant be solved
      if (!board.isValid()) {
         System.out.println("This board cannot be solved.");
      } else if (board.isSolved()) {
         // checks if board is alr solved and if alr solved prints alr solved
         System.out.println("This board is already solved.");
      } else {
         // if valid and not solved continues to try n solve board
         System.out.print("Solving board...");
         long start = System.currentTimeMillis();
         board.solve();
         long stop = System.currentTimeMillis();
         System.out.printf("SOLVED in %.3f seconds.\n", ((stop-start)/1000.0));
         System.out.println();
         System.out.println(board);
      }




      
   }
}



